import type { Params } from "./types";
export type RecipeNode = string | [string, Params];
export type Recipe = {
  nodes: RecipeNode[];
  edges: [number, number, string?][];
};
export type ExampleTemplate = {
  id: string;
  name: string;
  category: string;
  level: "入门" | "进阶";
  description: string;
  learn: string;
  requires?: "audio" | "ai" | "mcp";
  recipe?: Recipe;
  count?: number;
};
const chain = (...nodes: RecipeNode[]): Recipe => {
  const all: RecipeNode[] = [...nodes, "output"];
  return { nodes: all, edges: all.slice(1).map((_, i) => [i, i + 1]) };
};
const graph = (
  nodes: RecipeNode[],
  edges: [number, number, string?][],
): Recipe => ({ nodes, edges });
