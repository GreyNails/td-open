import type { NodeSpec, Param, Port } from "../types";
const num = (
  key: string,
  label: string,
  value: number,
  min = -100,
  max = 100,
  step = 0.01,
): Param => ({ key, label, type: "number", default: value, min, max, step });
const txt = (key: string, label: string, value = ""): Param => ({
  key,
  label,
  type: "text",
  default: value,
});
const pick = (
  key: string,
  label: string,
  value: string,
  options: string[],
): Param => ({ key, label, type: "select", default: value, options });
const flag = (key: string, label: string, value: boolean): Param => ({
  key,
  label,
  type: "boolean",
  default: value,
});
const port = (id: string, kind: string, label: string): Port => ({
  id,
  kind,
  label,
});
