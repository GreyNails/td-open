import type { NodeSpec, Param, Port } from "../types";
const n = (
  key: string,
  label: string,
  value: number,
  min = -10000,
  max = 10000,
  step = 0.01,
): Param => ({ key, label, type: "number", default: value, min, max, step });
const t = (key: string, label: string, value = ""): Param => ({
  key,
  label,
  type: "text",
  default: value,
});
const s = (
  key: string,
  label: string,
  value: string,
  options: string[],
): Param => ({ key, label, type: "select", default: value, options });
const b = (key: string, label: string, value = false): Param => ({
  key,
  label,
  type: "boolean",
  default: value,
});
const port = (id: string, kind: string, label: string): Port => ({
  id,
  kind,
  label,
});
const a = port("in", "CHOP", "通道"),
  a2 = port("in2", "CHOP", "第二组通道"),
  d = port("in", "DAT", "表格 / 文本"),
  d2 = port("in2", "DAT", "第二张表格");
const spec = (
  type: string,
  label: string,
  english: string,
  family: string,
  description: string,
  params: Param[] = [],
  inputs: Port[] = [],
  output = family,
): NodeSpec => ({
  type,
  label,
  english,
  family,
  description,
  params,
  inputs,
  outputs: [
    port("out", output, output === "CHOP" ? "命名采样通道" : "表格 / 文本"),
  ],
});
const ch = (
  type: string,
  label: string,
  english: string,
  description: string,
  params: Param[] = [],
  inputs: Port[] = [a],
) => spec(type, label, english, "CHOP", description, params, inputs);
const dat = (
  type: string,
  label: string,
  english: string,
  description: string,
  params: Param[] = [],
  inputs: Port[] = [d],
) => spec(type, label, english, "DAT", description, params, inputs);
