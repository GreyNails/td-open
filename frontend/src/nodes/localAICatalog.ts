export const localNodeProfile = (
  type: string,
  params: Record<string, unknown>,
): string => {
  if (type === "local_image") return String(params.model_id || "flux-klein-4b");
  if (type === "local_image_edit") return "flux-klein-4b";
  if (["local_image_to_image", "local_inpaint"].includes(type))
    return "z-image-turbo";
  if (type === "local_music") return "ace-step-15";
  if (type === "local_3d") return "hunyuan3d-21";
  if (type === "local_stems") return String(params.model_id || "demucs-4");
  if (type === "local_video") return "wan22-5b";
  return "";
};
