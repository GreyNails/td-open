import type { NodeSpec, Param, Port } from "../types";

const n = (
  key: string,
  label: string,
  value: number,
  min: number,
  max: number,
  step = 0.01,
): Param => ({ key, label, type: "number", default: value, min, max, step });
const c = (key: string, label: string, value: string): Param => ({
  key,
  label,
  type: "color",
  default: value,
});
const s = (
  key: string,
  label: string,
  value: string,
  options: string[],
): Param => ({ key, label, type: "select", default: value, options });
