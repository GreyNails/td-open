import type { NodeSpec, Param, Port } from "../types";
const num = (
    key: string,
    label: string,
    value: number,
    min = -100,
    max = 100,
    step = 0.01,
  ): Param => ({ key, label, type: "number", default: value, min, max, step }),
  pick = (
    key: string,
    label: string,
    value: string,
    options: string[],
  ): Param => ({ key, label, type: "select", default: value, options }),
  flag = (key: string, label: string, value = false): Param => ({
    key,
    label,
    type: "boolean",
    default: value,
  }),
  text = (key: string, label: string, value = ""): Param => ({
    key,
    label,
    type: "text",
    default: value,
  });
const input: Port = { id: "in", kind: "COMP", label: "场景" },
  vec = (prefix: string, value = 0) => [
    num(prefix + "x", "X", value),
    num(prefix + "y", "Y", value),
    num(prefix + "z", "Z", value),
  ],
  spec = (
    type: string,
    label: string,
    english: string,
    description: string,
    params: Param[],
    inputs: Port[] = [input],
  ): NodeSpec => ({
    type,
    label,
    english,
    description,
    family: "COMP",
    params,
    inputs,
    outputs: [{ id: "out", kind: "COMP", label: "场景" }],
  });
