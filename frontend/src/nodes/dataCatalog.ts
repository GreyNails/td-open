import type { NodeSpec, Param, Port } from "../types";

const num = (
  key: string,
  label: string,
  value: number,
  min = -100,
  max = 100,
  step = 0.01,
): Param => ({ key, label, type: "number", default: value, min, max, step });
const txt = (key: string, label: string, value = ""): Param => ({
  key,
  label,
  type: "text",
  default: value,
});
const choice = (
  key: string,
  label: string,
  value: string,
  options: string[],
): Param => ({ key, label, type: "select", default: value, options });
const flag = (key: string, label: string, value: boolean): Param => ({
  key,
  label,
  type: "boolean",
  default: value,
});
const port = (id: string, kind: string, label: string): Port => ({
  id,
  kind,
  label,
});
const signal = port("in", "CHOP", "数值"),
  signal2 = port("in2", "CHOP", "第二路"),
  text = port("in", "DAT", "文本"),
  geometry = port("in", "SOP", "几何体");
function spec(
  type: string,
  label: string,
  english: string,
  family: string,
  description: string,
  params: Param[],
  inputs: Port[] = [],
  outputKind = family,
): NodeSpec {
  return {
    type,
    label,
    english,
    family,
    description,
    params,
    inputs,
    outputs: [
      port(
        "out",
        outputKind,
        outputKind === "CHOP"
          ? "数值"
          : outputKind === "SOP"
            ? "几何体"
            : "文本",
      ),
    ],
  };
}
